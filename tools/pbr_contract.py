"""Validate authored Stylized PBR scalars and emit a transfer contract + numerical PNG probe.
Python 3.10+, standard library. This does not run Blender, Unity or establish visual parity.
"""
from __future__ import annotations
import argparse, copy, json, math, re, struct, zlib
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]

def unit(value, name: str) -> float:
    if isinstance(value, bool) or not isinstance(value, (float,int)) or not math.isfinite(value) or not 0 <= value <= 1:
        raise ValueError(f'{name}: expected finite number in [0,1]')
    return float(value)

def srgb_to_linear(value: float) -> float:
    v=unit(value,'sRGB'); return v/12.92 if v<=0.04045 else ((v+0.055)/1.055)**2.4

def linear_to_srgb(value: float) -> float:
    v=unit(value,'linear'); return 12.92*v if v<=0.0031308 else 1.055*v**(1/2.4)-0.055

def validate_library(data: dict) -> dict:
    if not isinstance(data,dict) or type(data.get('schema_version')) is not int or data.get('schema_version')!=1: raise ValueError('Unsupported material schema')
    mats=data.get('materials')
    if not isinstance(mats,dict) or not mats or len(mats)>64: raise ValueError('Expected 1..64 shared materials')
    for name,mat in mats.items():
        if not isinstance(name,str) or not re.fullmatch(r'[a-z][a-z0-9_]{0,50}',name): raise ValueError('Unsafe material ID')
        if not isinstance(mat,dict):raise ValueError('Material must be an object')
        if not isinstance(mat.get('srgb'),str) or not re.fullmatch(r'[A-Fa-f0-9]{6}',mat['srgb']):raise ValueError(f'{name}: invalid hex color')
        rough=unit(mat.get('roughness'),name+'.roughness');metal=unit(mat.get('metallic'),name+'.metallic')
        cls=mat.get('class')
        if cls not in ('dielectric','uncoated_metal'):raise ValueError('First probe allows explicit dielectric or bare metal only')
        if (cls=='dielectric' and metal!=0) or (cls=='uncoated_metal' and metal!=1):raise ValueError('Surface class and metallic disagree')
    return copy.deepcopy(data)

def load_library(path:Path|None=None)->dict:
    p=path or ROOT/'data/pbr_materials.json'
    return validate_library(json.loads(p.read_text(encoding='utf-8')))

def packed_pixel(metallic:float, roughness:float, occlusion:float=1)->tuple[int,int,int,int]:
    # Numerical data, NOT sRGB. Round-half-up so the fixture is independent of bankers rounding.
    enc=lambda x:int(math.floor(unit(x,'channel')*255+0.5))
    return enc(metallic),enc(occlusion),0,enc(1-unit(roughness,'roughness'))

def build_contract(data:dict)->dict:
    data=validate_library(data);out=[]
    for name,m in sorted(data['materials'].items()):
        rgb=[int(m['srgb'][i:i+2],16)/255 for i in (0,2,4)]
        out.append({'id':name,'blender_name':'ITPU_'+name,'base_color_srgb_hex':m['srgb'].upper(),
                    'base_color_linear_rgb':[srgb_to_linear(v) for v in rgb],
                    'roughness':m['roughness'],'metallic':m['metallic'],
                    'unity_smoothness_scalar_without_map':1-m['roughness'],
                    'unity_smoothness_multiplier_with_map':1,
                    'packed_data_rgba8':list(packed_pixel(m['metallic'],m['roughness'])),
                    'surface':'opaque','class':m['class']})
    return {'schema_version':1,'status':'NUMERIC_CONTRACT_NOT_ENGINE_VALIDATION',
            'layout':{'R':'metallic','G':'occlusion','B':'unused_zero','A':'smoothness'},
            'data_texture_srgb':False,'base_texture_srgb':True,
            'shader_target':'URP Lit Metallic (exact version needs probe)',
            'normal_map':'not generated by this tool',
            'material_scalar_color_import':'Verify single color conversion in a grey-ramp engine probe; do not blindly convert twice.',
            'entries':out,'blender':'NOT_RUN','unity':'NOT_RUN','quest':'NOT_RUN'}

def png_rgba(width:int,height:int,pixels:list[tuple[int,int,int,int]])->bytes:
    if isinstance(width,bool)or isinstance(height,bool)or not isinstance(width,int)or not isinstance(height,int)or not 1<=width<=256 or not 1<=height<=256:
        raise ValueError('Small probe dimensions expected (1..256)')
    if len(pixels)!=width*height:raise ValueError('Pixel count mismatch')
    for p in pixels:
        if len(p)!=4 or any(isinstance(v,bool) or not isinstance(v,int)or not 0<=v<=255 for v in p):raise ValueError('Invalid RGBA byte')
    def chunk(kind,payload):return struct.pack('!I',len(payload))+kind+payload+struct.pack('!I',zlib.crc32(kind+payload)&0xffffffff)
    rows=b''.join(b'\0'+bytes(v for p in pixels[y*width:(y+1)*width] for v in p)for y in range(height))
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('!IIBBBBB',width,height,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(rows))+chunk(b'IEND',b'')

def write_probe(out:Path,data:dict)->dict:
    contract=build_contract(data)
    if out.exists():raise ValueError('Output exists; choose a new directory, never overwrite accepted data')
    pixels=[packed_pixel(m,r)for m in (0,1)for r in (0,.25,.5,.75,1)]
    out.mkdir(parents=True)
    (out/'material_transfer.json').write_text(json.dumps(contract,ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
    (out/'calibration_data.png').write_bytes(png_rgba(5,2,pixels))
    (out/'README.txt').write_text('Numerical 5x2 RGBA fixture, not a campus texture. Rows: metallic 0/1; columns: roughness 0/.25/.5/.75/1. G=255 (AO), B=0, A=255..0 (smoothness). Disable sRGB for this data texture in Unity; visual test still NOT_RUN.\n',encoding='utf-8')
    return contract

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--out',type=Path,required=True);p.add_argument('--library',type=Path);a=p.parse_args()
    c=write_probe(a.out.resolve(),load_library(a.library));print(f'Prepared {len(c["entries"])} numeric contracts. Blender/Unity/Quest NOT_RUN.')
if __name__=='__main__':main()
